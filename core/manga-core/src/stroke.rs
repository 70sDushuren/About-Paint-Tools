//! High-frequency stylus input model (Apple Pencil Pro 240Hz + predicted touches)
//! and real-time Rope Stabilizer for smooth anime lineart inking.

/// Normalized stylus sample received from a hardware-native shell
/// (e.g., UIKit `UITouch` coalesced & predicted samples on iPadOS).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct StrokePoint {
    pub x: f32,
    pub y: f32,
    /// Normalized pen pressure in `[0.0, 1.0]`.
    pub pressure: f32,
    /// Pen altitude angle in radians (`PI/2` is perpendicular to screen).
    pub altitude: f32,
    /// Pen azimuth angle in radians around the canvas normal.
    pub azimuth: f32,
    /// Apple Pencil Pro barrel roll angle in radians.
    pub roll_angle: f32,
    /// Monotonic sample timestamp in milliseconds.
    pub timestamp_ms: f64,
    /// True if generated by OS touch prediction (`predictedTouches`) and subject to rollback.
    pub is_predicted: bool,
}

impl StrokePoint {
    pub fn simple(x: f32, y: f32, pressure: f32) -> Self {
        Self {
            x,
            y,
            pressure: pressure.clamp(0.0, 1.0),
            altitude: std::f32::consts::FRAC_PI_2,
            azimuth: 0.0,
            roll_angle: 0.0,
            timestamp_ms: 0.0,
            is_predicted: false,
        }
    }
}

/// Real-time Rope ("Pulled String") Stabilizer.
///
/// The virtual brush head trails behind the stylus tip on a virtual string of
/// length `radius`. Small hand tremors inside the radius are suppressed without
/// introducing laggy overshoot on long sweeping anime hair/contour arcs.
#[derive(Debug, Clone)]
pub struct RopeStabilizer {
    radius: f32,
    anchor: Option<(f32, f32)>,
}

impl RopeStabilizer {
    pub fn new(radius: f32) -> Self {
        Self {
            radius: radius.max(0.0),
            anchor: None,
        }
    }

    pub fn reset(&mut self) {
        self.anchor = None;
    }

    /// Feeds a raw stylus sample and returns a stabilized point if the rope moved.
    pub fn push(&mut self, input: StrokePoint) -> Option<StrokePoint> {
        if self.radius <= f32::EPSILON {
            self.anchor = Some((input.x, input.y));
            return Some(input);
        }

        let Some((ax, ay)) = self.anchor else {
            self.anchor = Some((input.x, input.y));
            return Some(input);
        };

        let dx = input.x - ax;
        let dy = input.y - ay;
        let dist = (dx * dx + dy * dy).sqrt();

        if dist <= self.radius {
            return None;
        }

        let pull = dist - self.radius;
        let nx = ax + (dx / dist) * pull;
        let ny = ay + (dy / dist) * pull;
        self.anchor = Some((nx, ny));

        Some(StrokePoint {
            x: nx,
            y: ny,
            ..input
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rope_stabilizer_suppresses_micro_jitter_within_radius() {
        let mut stab = RopeStabilizer::new(6.0);
        let p0 = stab.push(StrokePoint::simple(100.0, 100.0, 0.5));
        assert!(p0.is_some());

        // Jitter within 6px radius should emit no erratic point.
        assert!(stab.push(StrokePoint::simple(103.0, 102.0, 0.5)).is_none());
        assert!(stab.push(StrokePoint::simple(98.0, 101.0, 0.5)).is_none());

        // Dragging 16px right pulls the anchor by 10px to x = 110.
        let p1 = stab.push(StrokePoint::simple(116.0, 100.0, 0.8)).unwrap();
        assert!((p1.x - 110.0).abs() < 1e-4);
        assert!((p1.y - 100.0).abs() < 1e-4);
        assert!((p1.pressure - 0.8).abs() < 1e-6);
    }

    #[test]
    fn zero_radius_passes_points_through_unmodified() {
        let mut stab = RopeStabilizer::new(0.0);
        let raw = StrokePoint::simple(42.5, 19.25, 0.7);
        assert_eq!(stab.push(raw), Some(raw));
    }
}
